def from_argv(argv):
    p = dict(P)
    for a in argv:
        if a.startswith('--') and '=' in a:
            k, v = a[2:].split('=', 1)
            if k in p: p[k] = type(p[k])(float(v)) if not isinstance(p[k], int) else int(float(v))
    p['SLOT_W'] = p['T'] + p['SLOT_CLR']
    return p
